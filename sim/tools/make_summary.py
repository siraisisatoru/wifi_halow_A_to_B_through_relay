"""Write sim/results/SUMMARY.md from every <scenario>/summary.json under a results directory.

    make_summary.py sim/results
Exit status 1 when any per-scenario or cross-scenario check failed.
"""

import datetime
import json
import os
import sys

ORDER = ["baseline_direct", "relay_nominal", "relay_lossy", "relay_outage", "relay_saturation",
         "direct_saturation"]


def fmt(v, nd=1):
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def load_all(root):
    out = {}
    for name in os.listdir(root):
        p = os.path.join(root, name, "summary.json")
        if os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                out[name] = json.load(f)
    names = [n for n in ORDER if n in out] + sorted(n for n in out if n not in ORDER)
    return names, out


def cross_checks(s):
    checks = []

    def p50(name, flow="udp"):
        return s.get(name, {}).get("flows", {}).get(flow, {}).get("rtt_p50_ms")

    if p50("baseline_direct") and p50("relay_nominal"):
        d, rl = p50("baseline_direct"), p50("relay_nominal")
        checks.append(("relay_nominal UDP RTT p50 > baseline_direct UDP RTT p50",
                       f"{rl:.1f} ms vs {d:.1f} ms", rl > d))
    rs = s.get("relay_saturation", {}).get("sweep")
    ds = s.get("direct_saturation", {}).get("sweep")
    if rs and ds and ds.get("max_delivered_pps"):
        ratio = rs["max_delivered_pps"] / ds["max_delivered_pps"]
        checks.append(("relay capacity / direct capacity about 0.5 (single-radio store-and-forward)",
                       f"{ratio:.2f}", 0.4 <= ratio <= 0.6))
    out = s.get("relay_outage")
    if out:
        lost = out["flows"].get("udp", {}).get("lost")
        rate = out["flows"].get("udp", {}).get("rate") or 10
        win = out.get("link_windows", [{}])[0]
        dur = (win.get("up_s", 0) - win.get("down_s", 0)) if win else 0
        if lost is not None and dur:
            checks.append(("relay_outage UDP loss matches the outage length",
                           f"{lost} lost = {lost / rate:.1f} s at {rate} pps; outage {dur:.1f} s",
                           abs(lost / rate - dur) <= 2.0))
    return checks


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "sim/results"
    names, s = load_all(root)
    calib = {}
    cp = os.path.join(root, "calibration.json")
    if os.path.exists(cp):
        with open(cp, encoding="utf-8") as f:
            calib = json.load(f)
    L = []
    w = L.append
    w("<!--\nCopyright 2026 siraisisatoru\nSPDX-License-Identifier: Apache-2.0\n-->\n")
    w("# Host network simulation: results\n")
    kern = next((s[n].get("netsim", {}).get("kernel") for n in names), None)
    w(f"Generated by `sim/run_sim.sh` on {datetime.date.today().isoformat()} (kernel {kern}). "
      "The model and its assumptions are described in [../README.md](../README.md). "
      "These are model numbers for planning and for checking the tooling, not measurements of the "
      "boards.\n")
    if calib:
        w(f"Timer calibration: each netem stage in this VM adds about {calib['stage_extra_ms']:.2f} ms, "
          "which is subtracted from every configured hop delay.\n")

    w("## Scenarios\n")
    w("| Scenario | Topology | What it models |")
    w("|---|---|---|")
    for n in names:
        sc = s[n].get("scenario", {})
        w(f"| [{n}]({n}/) | {sc.get('topology', '-')} | {sc.get('description', '')} |")
    w("")

    w("## Latency, loss and TCP recovery\n")
    w("UDP: 10 echo requests/s, 64 B payload. TCP: 5 messages/s, 256 B. Ping: every 200 ms, 56 B. "
      "UDP RTT percentiles are exact per-packet values from a capture on A; ping percentiles are "
      "from the ping samples.\n")
    w("| Scenario | UDP loss % (uplink %) | UDP RTT p50 / p95 / max (ms) | UDP jitter (ms) "
      "| A→relay UDP RTT p50 (ms) | ping A→B p50 / p95 (ms), loss % | TCP ACKed / sent "
      "| TCP reconnects | TCP recovery after link up (s) | goodput UDP / TCP (kbit/s) |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for n in names:
        if s[n].get("sweep"):
            continue
        f = s[n]["flows"]
        d = s[n].get("derived", {})
        u, us, ur, pb, t = (f.get(k, {}) for k in ("udp", "udp_srv", "udp_relay", "ping_node_b", "tcp"))
        w(f"| {n} | {fmt(u.get('loss_pct'), 2)} ({fmt(us.get('loss_pct'), 2)}) "
          f"| {fmt(u.get('rtt_p50_ms'))} / {fmt(u.get('rtt_p95_ms'))} / {fmt(u.get('rtt_max_ms'))} "
          f"| {fmt(u.get('jitter_ms'), 2)} | {fmt(ur.get('rtt_p50_ms'))} "
          f"| {fmt(pb.get('rtt_p50_ms'))} / {fmt(pb.get('rtt_p95_ms'))}, {fmt(pb.get('loss_pct'), 1)} "
          f"| {fmt(t.get('rcvd'))} / {fmt(t.get('sent'))} | {fmt(t.get('reconnects'))} "
          f"| {fmt(d.get('tcp_recovery_after_link_up_s'), 2)} "
          f"| {fmt(u.get('goodput_kbps'), 1)} / {fmt(t.get('goodput_kbps'), 1)} |")
    w("")

    out = s.get("relay_outage")
    if out:
        t = out["flows"].get("tcp", {})
        d = out.get("derived", {})
        win = out.get("link_windows", [{}])[0]
        w("### relay_outage timeline\n")
        w(f"- R-B link down at {fmt(win.get('down_s'), 2)} s, up at {fmt(win.get('up_s'), 2)} s.")
        w(f"- Longest gap between UDP echoes at A: {fmt(d.get('udp_longest_gap_s'), 2)} s; "
          f"UDP lost {out['flows'].get('udp', {}).get('lost')} (uplink "
          f"{out['flows'].get('udp_srv', {}).get('lost')}): every request sent while the link was "
          "down never reached B.")
        w(f"- TCP stall detected {fmt(d.get('tcp_detect_after_link_down_s'), 2)} s after the link "
          f"went down (ack timeout 5 s); reconnected {fmt(d.get('tcp_recovery_after_link_up_s'), 2)} s "
          f"after it came back; outage seen by the client {fmt(d.get('tcp_outage_ms_max'))} ms; "
          f"{t.get('lost')} messages were outstanding at the drop and are counted as lost.")
        for e in t.get("connection_events", []):
            extra = ", ".join(f"{k}={e[k]}" for k in ("reason", "attempt", "connect_ms", "outage_ms",
                                                      "unacked", "err", "retry_ms") if k in e)
            w(f"  - {fmt(e.get('t_s'), 2)} s `{e['ev']}` {extra}")
        w("")

    for n in names:
        sw = s[n].get("sweep")
        if not sw:
            continue
        w(f"## {n}\n")
        w(f"Model capacity {fmt(sw.get('model_capacity_pps'))} echo/s; highest delivered "
          f"{fmt(sw.get('max_delivered_pps'))} echo/s = {fmt(sw.get('max_goodput_kbps_per_dir'))} kbit/s "
          f"of payload per direction; highest rate with < 1 % loss: {fmt(sw.get('max_rate_loss_below_1pct'))} "
          "requests/s.\n")
        w("| Offered (req/s) | Offered (kbit/s per dir) | Delivered (echo/s) | Loss % | RTT p50 / p95 / max (ms) |")
        w("|---|---|---|---|---|")
        for st in sw["steps"]:
            w(f"| {st['rate_pps']} | {st['rate_pps'] * (st['payload'] or 0) * 8 / 1000:.0f} "
              f"| {fmt(st['delivered_pps'])} | {fmt(st['loss_pct'], 2)} "
              f"| {fmt(st['rtt_p50_ms'])} / {fmt(st['rtt_p95_ms'])} / {fmt(st['rtt_max_ms'])} |")
        w("")

    w("## Checks\n")
    failed = 0
    w("| Scenario | Check | Value | Expected | Result |")
    w("|---|---|---|---|---|")
    for n in names:
        for c in s[n].get("checks", []):
            failed += not c["ok"]
            w(f"| {n} | `{c['metric']}` | {fmt(c['value'], 3)} | {c['expect']} | "
              f"{'PASS' if c['ok'] else 'FAIL'} |")
        g = s[n].get("netsim", {})
        if g.get("root_group_tx_dropped") is not None:
            ok = g.get("root_group_selftest_dropped", 0) >= 1
            failed += not ok
            w(f"| {n} | bug #10 model active (self-test broadcast from B dropped) "
              f"| {g.get('root_group_selftest_dropped')} | >= 1 | {'PASS' if ok else 'FAIL'} |")
            w(f"| {n} | group-addressed frames B tried to send during the run (dropped) "
              f"| {g.get('root_group_tx_dropped')} | info | - |")
    for desc, val, ok in cross_checks(s):
        failed += not ok
        w(f"| all | {desc} | {val} | | {'PASS' if ok else 'FAIL'} |")
    w("")

    w("## Plots\n")
    for p in ("rtt_compare.png", "saturation_compare.png"):
        if os.path.exists(os.path.join(root, p)):
            w(f"![{p}]({p})\n")
    for n in names:
        pngs = sorted(x for x in os.listdir(os.path.join(root, n)) if x.endswith(".png"))
        if pngs:
            w(f"- {n}: " + ", ".join(f"[{x}]({n}/{x})" for x in pngs))
    w("")

    with open(os.path.join(root, "SUMMARY.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print(f"wrote {os.path.join(root, 'SUMMARY.md')} ({failed} failed checks)")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
